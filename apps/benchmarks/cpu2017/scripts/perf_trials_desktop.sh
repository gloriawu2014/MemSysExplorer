#!/bin/bash

# -------- Configurable Paths --------
CMD_DIR="/home/gloriawu/MemSysExplorer/apps/benchmarks/cpu2017/commands"
FILTER_DIR="fprate"
RUN_TYPE="refrate"
LEVEL="l3"
OPTIMIZATION="O2"
SPEC_ROOT="/home/gloriawu/cpu2017"

CMD_TYPE=$(echo "$RUN_TYPE" | sed 's/rate//')

# -------- Loop through .cmd files to identify benchmark directories --------
find "$CMD_DIR/$FILTER_DIR" -name "*.${CMD_TYPE}.cmd" | while read -r CMD_FILE; do
    BENCH_ID=$(basename "$CMD_FILE" .${CMD_TYPE}.cmd)
    COPY_DIR="$SPEC_ROOT/benchspec/CPU/$BENCH_ID/run/${LEVEL}_${OPTIMIZATION}"

    if [ ! -d "$COPY_DIR" ]; then
        echo "Skipping $BENCH_ID: Directory $COPY_DIR does not exist."
        continue
    fi

    cd "$COPY_DIR" || continue
    echo "==> Managing trials for $BENCH_ID"

    # 1. Determine the next trial number
    # Counts directories named 'trial_' and adds 1
    CURRENT_TRIALS=$(ls -vd trial_* 2>/dev/null | wc -l)
    NEXT_TRIAL=$((CURRENT_TRIALS + 1))
    NEW_FOLDER="trial_${NEXT_TRIAL}"
    mkdir -p "$NEW_FOLDER"

    RUN_SH="${BENCH_ID}.${RUN_TYPE}.sh"

    if [ ! -f "$RUN_SH" ]; then
        echo "Skipping $BENCH_ID: $RUN_SH not found in $(pwd)"
        cd - > /dev/null
        continue
    fi

    # 2. Check if there is actually work to move
    # This looks for strings ending in these extensions inside the shell script
    TARGET_FILES=$(grep "^python3" "$RUN_SH" | grep -oP '(?<!2)>+ \s*\K\S+' | grep -v "\.err$")

    # 3. Move the extracted files + any memsys files
    for FILE in $TARGET_FILES; do
        if [[ -f "$FILE" && "$FILE" != "$RUN_SH" ]]; then
            mv "$FILE" "$NEW_FOLDER/"
            echo "    → Moved $FILE"
        fi
    done

    # Also move memsys files (as they are usually generated by the main.py tool)
    if ls memsys* >/dev/null 2>&1; then
        mv memsys* "$NEW_FOLDER/"
        echo "    → Moved memsys files"
    fi

    #rm -rf "$NEW_FOLDER"

    # 4. Resubmit
    echo "    → Resubmitting $RUN_SH"
    #sbatch "$RUN_SH"

    cd - > /dev/null
done
